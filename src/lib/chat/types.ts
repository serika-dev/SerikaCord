/**
 * Shared chat message types used by both server channels (ChatArea) and DMs.
 */
import type { CallMessageData } from "@/lib/voice/callMessage";
import type { GroupDmEventType } from "@/lib/chat/groupDm";
import type { ThreadSummary } from "@/lib/chat/threads";
import type { PollResultData, PollView } from "@/lib/chat/polls";
import type { ForwardView } from "@/lib/chat/forward";
import type { MessageComponent } from "@/lib/botapi/components";

export interface MessageAuthor {
  id: string;
  username: string;
  displayName: string;
  avatar?: string;
  badges?: string[];
  status?: "online" | "idle" | "dnd" | "offline";
  isPremium?: boolean;
  isOwner?: boolean;
  isSystem?: boolean;
  isBot?: boolean;
  isVerified?: boolean;
  isDiscord?: boolean;
  /** A channel webhook's post (the id is the webhook's, not a user's). */
  isWebhook?: boolean;
  customization?: {
    profileColor?: string;
    profileAccentColor?: string;
    profileGradient?: string[];
    displayNameStyle?: {
      font?: 'default' | 'serif' | 'mono' | 'rounded' | 'cursive' | 'bold';
      effect?: 'solid' | 'gradient' | 'neon' | 'toon' | 'pop';
      color?: string;
      gradient?: string[];
    };
    /** Resolved server tag (CORD-53), see lib/servers/serverProfile. */
    serverTag?: unknown;
  } | null;
}

export interface MessageAttachment {
  id: string;
  url: string;
  filename: string;
  contentType: string;
  size?: number;
  spoiler?: boolean;
  /** Flagged by the server's explicit media content filter: blurred until clicked. */
  sensitive?: boolean;
  /** Voice messages (flags & IS_VOICE_MESSAGE): length and base64 waveform. */
  durationSecs?: number;
  waveform?: string;
  /**
   * End-to-end encrypted file: `url` is the ciphertext blob; these decrypt it
   * in the browser (lib/e2ee). filename / contentType / size are the real ones.
   */
  e2ee?: { key: string; iv: string; sha256: string };
}

/** End-to-end encryption state of a message (decrypted in memory only). */
export interface MessageE2ee {
  status: "pending" | "ok" | "error";
  /** Why it couldn't be decrypted / verified (lib/e2ee/client DecryptFailure). */
  reason?: string;
  /** Sender device signature checked against a trusted identity key. */
  verified?: boolean;
  /** The stored envelope (kept so a cached copy or a failure can be decrypted again). */
  envelope?: unknown;
  /** Failures: the attachment blobs stored on the row (a retry checks payload files against them). */
  stored?: string[];
  /** Failures: automatic retries done so far (lib/e2ee/decryptRetry). */
  attempts?: number;
  /** Failures: a transient one that is still being retried (shown as "Decrypting…"). */
  retrying?: boolean;
}

export interface MessageReaction {
  emoji: {
    id?: string;
    name: string;
    animated?: boolean;
    url?: string;
  };
  count: number;
  userIds: string[];
}

export interface MessageCustomEmoji {
  id: string;
  name: string;
  animated?: boolean;
  url: string;
}

export interface MessageSticker {
  id: string;
  name: string;
  imageUrl: string;
  serverId?: string;
  serverName?: string;
}

/** Discord-compatible rich embed sent by bots (or generated by link unfurling). */
export interface MessageEmbed {
  title?: string;
  type?: string;
  description?: string;
  url?: string;
  /** Integer color (0xRRGGBB) for the left accent bar. */
  color?: number;
  timestamp?: string;
  footer?: { text?: string; icon_url?: string; iconUrl?: string };
  image?: { url?: string; width?: number; height?: number };
  thumbnail?: { url?: string; width?: number; height?: number };
  video?: { url?: string; width?: number; height?: number };
  provider?: { name?: string; url?: string };
  author?: { name?: string; url?: string; icon_url?: string; iconUrl?: string };
  fields?: { name: string; value: string; inline?: boolean }[];
}

export interface ReferencedMessage {
  id: string;
  content: string;
  author?: {
    id: string;
    username: string;
    displayName: string;
    avatar?: string;
    isBot?: boolean;
    isVerified?: boolean;
    isDiscord?: boolean;
    /** The reply points at a webhook post. */
    isWebhook?: boolean;
  };
  createdAt?: string;
  /** Users mentioned as <@id> in `content`, so the reply preview can name them (Discord's referenced_message.mentions). */
  mentions?: Array<{ id: string; username: string; displayName: string; avatar?: string; isBot?: boolean }>;
  /** The referenced message is end-to-end encrypted (its text comes from the reply's own envelope). */
  encrypted?: boolean;
  /** Custom emoji used in `content`, resolved by the server (rendered by id). */
  customEmojis?: MessageCustomEmoji[];
  /**
   * Encrypted: `content` is the snippet the replier put in their own message
   * (we couldn't decrypt the original here), so it is shown as their quote.
   */
  quotedBySender?: boolean;
}

export interface ChatMessage {
  id: string;
  content: string;
  type?: "default" | "reply" | "system" | "call" | "thread_created" | "poll_result" | "e2ee_enabled" | "e2ee_disabled" | "channel_pinned_message" | GroupDmEventType;
  authorId: string;
  author: MessageAuthor;
  channelId: string;
  createdAt: string;
  updatedAt?: string;
  edited?: boolean;
  pinned?: boolean;
  referencedMessageId?: string;
  referencedMessage?: ReferencedMessage;
  attachments?: MessageAttachment[];
  /** Rich embeds (bot-authored, or generated from links). */
  embeds?: MessageEmbed[];
  reactions?: MessageReaction[];
  customEmojis?: MessageCustomEmoji[];
  sticker?: MessageSticker;
  mentionEveryone?: boolean;
  mentionedUserIds?: string[];
  mentionedRoleIds?: string[];
  mentionedChannelIds?: string[];
  /** True while the message is an optimistic send awaiting server confirmation. */
  pending?: boolean;
  /** Ephemeral messages are only visible to the invoking user and are not persisted. */
  ephemeral?: boolean;
  /** Set on a bot's interaction response: who invoked which command (name is '' for button clicks). */
  interaction?: { id?: string; name: string; user: { id: string; username: string } };
  /** Bot message components: buttons, select menus, components v2 layouts (lib/botapi/components). */
  components?: MessageComponent[];
  /** When true, link previews and rich embeds are hidden for this message. */
  suppressEmbeds?: boolean;
  /** Discord message flags (lib/chat/messageFlags): SUPPRESS_NOTIFICATIONS = "@silent". */
  flags?: number;
  /** Set when an incoming channel webhook posted this message (authorId is then the webhook's id). */
  webhookId?: string;
  /** DM call log row (type "call"): who called, when, whether it was answered. */
  call?: CallMessageData | null;
  /** Group DM system row ("X added Y to the group."): who it's about, the new name. */
  groupEvent?: GroupEventData | null;
  /** Thread started from this message, or announced by this "started a thread" row. */
  threadId?: string;
  /** That thread's summary (chip: name, message count, last reply); null once deleted. */
  thread?: ThreadSummary | null;
  /** A poll message: question, answers, live tallies and the viewer's votes. */
  poll?: PollView | null;
  /** A "poll results" row (type "poll_result"): the frozen outcome. */
  pollResult?: PollResultData | null;
  /** A forwarded message: the frozen copy of the original. */
  forward?: ForwardView | null;
  /** End-to-end encrypted message (DMs / group DMs): decryption status. */
  e2ee?: MessageE2ee;
  /**
   * A message without an envelope in an end-to-end encrypted conversation
   * (after encryption was turned on): nobody can vouch for its sender.
   */
  e2eePlaintext?: boolean;
  /** "Turned off encryption" rows: the member-signed record (lib/e2ee/conversationState). */
  e2eeRecord?: unknown;
  /** "Turned off encryption" rows: whether that record verified on this device. */
  e2eeNoticeVerified?: boolean;
}

/** Details of a group DM system row (the actor is the message author). */
export interface GroupEventData {
  kind: GroupDmEventType;
  target?: { id: string; username: string; displayName: string; avatar?: string | null };
  /** channel_name_change: the new name ("" = name removed). */
  name?: string;
}

export interface MessageGroupData<M extends ChatMessage = ChatMessage> {
  author: MessageAuthor;
  timestamp: string;
  messages: M[];
}

/** Builds the emoji identifier the reactions API expects. */
export function reactionEmojiIdentifier(emoji: MessageReaction["emoji"]): string {
  return emoji.id ? `<${emoji.animated ? "a" : ""}:${emoji.name}:${emoji.id}>` : emoji.name;
}
