/** Groups a ranking by tier, keeping the best-to-worst order inside each tier. */
export function groupByTier(ranking: Ranking): Record<Tier, TierAppId[]> {
  const out = Object.fromEntries(TIERS.map((t) => [t, [] as TierAppId[]])) as Record<Tier, TierAppId[]>;
  for (const [app, tier] of ranking) out[tier].push(app);
  return out;
}

/** An app's tier in a ranking (undefined if it isn't ranked there). */
export function tierOf(ranking: Ranking, app: TierAppId): Tier | undefined {
  return ranking.find(([id]) => id === app)?.[1];
}

/** Numeric value of a tier, S = 5 ... F = 0. */
export function tierScore(tier: Tier): number {
  return TIERS.length - 1 - TIERS.indexOf(tier);
}
