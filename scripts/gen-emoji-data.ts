/**
 * Regenerates src/lib/chat/emojiData.generated.ts from the English emoji
 * dataset that ships with emoji-picker-react (already a dependency):
 * every emoji with its CLDR name (as a shortcode), search keywords and
 * whether it takes a skin-tone modifier.
 *
 *   bun scripts/gen-emoji-data.ts
 *
 * Discord shortcodes and common aliases live in src/lib/chat/emojiAliases.ts
 * and are layered on top at runtime (src/lib/chat/emojiIndex.ts).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface RawEmoji {
  n: string[];
  u: string;
  v?: string[];
}

const root = join(import.meta.dir, "..");
const source = join(root, "node_modules/emoji-picker-react/dist/data/emojis-en.json");
const out = join(root, "src/lib/chat/emojiData.generated.ts");

const data = JSON.parse(readFileSync(source, "utf8")) as { emojis: Record<string, RawEmoji[]> };
const TONES = ["1f3fb", "1f3fc", "1f3fd", "1f3fe", "1f3ff"];

const toChar = (u: string) => u.split("-").map((p) => String.fromCodePoint(parseInt(p, 16))).join("");

export function snake(name: string): string {
  return name
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[’'".!()“”,]/g, "")
    .replace(/\*/g, " asterisk ")
    .replace(/#/g, " hash ")
    .replace(/[^a-z0-9+]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

/** The tone variant the modifier rule in emojiIndex.applySkinTone produces. */
function toneRule(u: string, tone: string): string {
  const parts = u.split("-");
  const rest = parts.slice(1);
  if (rest[0] === "fe0f") rest.shift();
  return [parts[0], tone, ...rest].join("-");
}

const rows: string[] = [];
const seenNames = new Set<string>();
let skinMismatch = 0;
for (const [category, list] of Object.entries(data.emojis)) {
  if (category === "custom") continue;
  for (const e of list) {
    const cldr = e.n[e.n.length - 1] ?? "";
    let name = snake(cldr.replace(/^flag: /, "flag "));
    if (!name || seenNames.has(name)) name = "";
    if (name) seenNames.add(name);
    const nameWords = new Set(name.split("_"));
    const keywords = [...new Set(e.n.slice(0, -1).map((k) => k.toLowerCase().trim()))]
      .filter((k) => k && !nameWords.has(k) && !/^flag: /.test(k) && /^[a-z0-9+ '-]+$/.test(k))
      .join(" ");
    let skin = 0;
    if (e.v && e.v.length >= 5) {
      const ok = TONES.every((t, i) => e.v![i] === toneRule(e.u, t));
      if (ok) skin = 1;
      else skinMismatch++;
    }
    rows.push(`[${JSON.stringify(toChar(e.u))},${JSON.stringify(name)},${JSON.stringify(keywords)},${skin}]`);
  }
}

const header = `// GENERATED by scripts/gen-emoji-data.ts from emoji-picker-react's English
// dataset. Do not edit by hand; Discord names and aliases go in emojiAliases.ts.
// Row: [emoji, CLDR shortcode, search keywords (space separated), takes a skin tone (1) or not (0)].
export type EmojiDataRow = readonly [string, string, string, 0 | 1];
export const EMOJI_DATA: readonly EmojiDataRow[] = [
`;
writeFileSync(out, header + rows.join(",\n") + "\n];\n");
console.log(`wrote ${rows.length} emoji to ${out} (${skinMismatch} skin-tone sets skipped)`);
